# ---------------------------------------------------------------- 重复度的实现细节（照 datatrove）


def test_dup_ngram_skips_after_a_match():
    """找到重复就跳过这 n 个 token：a b c a b c a b c 里，后两组 "a b c" 各记一次，共 2×5 个字符。
    如果不跳过、每个位置都算，重叠的 "b c a"、"c a b" 也会被计入，结果偏大。"""
    toks = "a b c a b c a b c".split()
    assert F._dup_ngram_chars(toks, 3, " ") == 2 * len("a b c")


def test_repetition_divides_by_whole_text_length():
    """分母是整篇文本的字符数：加上大量空白，重复占比就被稀释。"""
    lines = "\n".join(["same line here"] * 3 + [f"unique line {i}" for i in range(7)])
    assert F.repetition(lines) is None                  # 2/10 行重复，按条数没超 30%
    heavy = "\n".join(["same line here"] * 5 + ["x"])
    assert F.repetition(heavy) == "重复行（按行数）"     # 4/6 行重复


