def test_chinese_article_repeating_a_long_term_passes():
    """正常报道里一个 12 字的术语出现 6 次，不能当成重复。

    n×1 / n×2 / n×3 在真实数据上的丢弃率差别（22% / 6.0% / 3.8%）来自长文章里大量自然出现的短重复，
    手写的小例子复现不出来，由 scripts/calibrate_filters.py 在真实文档上测。
    """
    term = "新型冠状病毒感染肺炎疫情"
    text = (
        f"本市{term}防控工作持续推进，各社区按照要求落实排查措施。"
        f"专家提醒，{term}期间应减少聚集，出门佩戴口罩并勤洗手。"
        f"学校方面表示，{term}形势稳定后将逐步恢复线下教学安排。"
        f"交通部门介绍，受{term}影响，部分公交线路的班次有所调整。"
        f"医院开设专门通道，方便与{term}相关的就诊人员快速分流。"
        f"志愿者说，{term}以来社区邻里之间互相帮助的氛围更浓了。"
        + ZH + ZH2
    )
    assert F.chinese(text) is None


