def test_math_ignores_many_short_repeated_ui_lines():
    """论坛页：几十个 "Reply" 按条数超标，但只占全文很小一部分，数学内容本身是好的。"""
    body = "\n".join(f"Step {i}: substitute x = {i} into the equation and simplify both sides carefully."
                     for i in range(20))
    page = body + "\n" + "\n".join(["Reply"] * 30)
    assert F.FILTERS["math"](page) is None
    assert F.light(page, by_count=True) == "重复行（按行数）"


def test_every_subset_has_a_filter():
    """抽样脚本里的每个来源都要有对应的规则，否则管线跑到一半才报 KeyError。"""
    import importlib.util
    import sys
    from pathlib import Path

    path = Path(__file__).resolve().parents[1] / "scripts" / "sample_tokenizer_corpus.py"
    spec = importlib.util.spec_from_file_location("sample", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod  # dataclass 需要能从 sys.modules 找到定义它的模块
    spec.loader.exec_module(mod)
    names = {s.name for s in mod.PARQUET_SOURCES} | {"en_web_dclm"}
    assert names == set(F.FILTERS)
